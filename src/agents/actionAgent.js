/**
 * agents/actionAgent.js
 * Posts the shared scan result to GitLab and sends the executive email brief.
 */

import logger from '../middleware/logger.js';
import { postMRComment, updateMRLabels } from '../tools/gitlabClient.js';
import { sendMRBrief } from '../tools/emailer.js';

const LABEL_MAP = {
  LOW: 'guardian:cleared',
  'MEDIUM-HIGH': 'guardian:review-required',
  CRITICAL: 'guardian:blocked',
};

const STATUS_EMOJI = {
  LOW: '✅',
  'MEDIUM-HIGH': '⚠️',
  CRITICAL: '🚨',
};

function riskDecision(level) {
  if (level === 'CRITICAL') return 'BLOCKED / CRITICAL';
  if (level === 'MEDIUM-HIGH') return 'REVIEW / MEDIUM-HIGH';
  return 'LOW';
}

export async function takeAction({ result, context, project, user }) {
  logger.info(`[Agent 6: Action Agent] Starting for MR !${result.mrId}`);
  const startTime = Date.now();
  const results = {
    commentPosted: false,
    commentId: null,
    suggestionsPosted: 0,
    labelApplied: null,
    emailSent: false,
  };

  if (result.status !== 'OK') {
    logger.warn(`[Agent 6] Skipping GitLab actions for failed MR !${result.mrId}`);
    return results;
  }

  try {
    const note = await postMRComment(
      result.projectId,
      result.mrId,
      buildDashboardComment(result)
    );
    results.commentPosted = true;
    results.commentId = note?.id;
    result.commentPosted = true;
    logger.info(`[Agent 6] Dashboard comment posted, note id: ${note?.id}`);
  } catch (err) {
    logger.error(`[Agent 6] Failed to post dashboard comment: ${err.message}`);
  }

  const actionableFindings = result.findings.filter(f =>
    (f.severity === 'critical' || f.severity === 'high') && f.fixedCode
  );
  for (const finding of actionableFindings.slice(0, 8)) {
    try {
      const emoji = finding.severity === 'critical' ? '🔴' : '🟠';
      const body = [
        `## ${emoji} Security Finding — ${finding.severity.toUpperCase()}`,
        '',
        `**Type:** \`${finding.type || 'unknown'}\` | **CWE:** ${finding.cweId || 'N/A'} | **File:** \`${finding.file || 'unknown'}\`${finding.line ? ` (line ${finding.line})` : ''}`,
        '',
        `**Issue:** ${finding.description}`,
        '',
        '**Vulnerable code:**',
        '```',
        finding.originalCode || '',
        '```',
        '',
        '**Suggested fix:**',
        '```',
        finding.fixedCode,
        '```',
        '',
        '_Auto-generated by Guardian AI · Apply this fix to resolve the security finding_',
      ].join('\n');
      await postMRComment(result.projectId, result.mrId, body);
      results.suggestionsPosted++;
    } catch (err) {
      logger.warn(`[Agent 6] Finding comment failed (non-fatal): ${err.message}`);
    }
  }

  try {
    const label = LABEL_MAP[result.riskLevel];
    await updateMRLabels(result.projectId, result.mrId, [label, 'guardian-ai-reviewed']);
    results.labelApplied = label;
    logger.info(`[Agent 6] Labels applied: ${label}`);
  } catch (err) {
    logger.error(`[Agent 6] Label update failed: ${err.message}`);
  }

  try {
    const mrUrl = context?.mrDetails?.web_url
      || `${process.env.GITLAB_API_URL?.replace('/api/v4', '')}/${result.projectId}/-/merge_requests/${result.mrId}`;
    const emailResult = await sendMRBrief({
      mr: context?.mrDetails || { iid: result.mrId, title: result.title, author: { name: result.author } },
      project,
      audit: { findings: result.findings },
      risk: { score: result.riskScore, label: result.riskLevel },
      green: { pipelinesSaved: result.pipelinesSaved, co2Saved: result.co2Grams },
      mrUrl,
      user,
    });
    results.emailSent = emailResult.sent;
    if (emailResult.sent) logger.info(`[Agent 6] Email sent, id: ${emailResult.id}`);
  } catch (err) {
    logger.error(`[Agent 6] Email send failed: ${err.message}`);
  }

  logger.info(`[Agent 6: Action Agent] Done in ${Date.now() - startTime}ms.`, results);
  return results;
}

function buildDashboardComment(result) {
  const emoji = STATUS_EMOJI[result.riskLevel];
  const findingsTable = result.findings.length
    ? [
        '',
        '### Security Findings',
        '',
        '| Severity | Type | File | Description |',
        '|----------|------|------|-------------|',
        ...result.findings.slice(0, 15).map(f =>
          `| ${(f.severity || 'low').toUpperCase()} | \`${f.type || 'unknown'}\` | \`${(f.file || 'unknown').split('/').pop()}\` | ${(f.description || '').slice(0, 80)} |`
        ),
      ].join('\n')
    : '\n> No security findings were reported.';

  return `## Guardian AI — MR Analysis Report

> **${emoji} ${riskDecision(result.riskLevel)}** · Score: **${result.riskScore}/100** · Findings: **${result.totalFindings}**

MR !${result.mrId}: ${result.title}
Author: ${result.author}

Critical findings: ${result.criticalCount}
Documentation updated: ${result.docsUpdated ? 'Yes' : 'No'}
Pipelines saved: ${result.pipelinesSaved}
CO₂ avoided: ${result.co2Grams}g
${findingsTable}

---
_Analyzed by Guardian AI at ${new Date(result.createdAt).toUTCString()}._`;
}
